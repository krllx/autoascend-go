"""Generate nle/nhdata_gen.go from nhdata.json (dumped by dump_data.py inside the arena image)."""
import json, sys
d = json.load(open(sys.argv[1]))
out = open(sys.argv[2], 'w')
w = out.write
w('// Code generated by tools/gen_go.py from the arena image (nle 1.3.0 + AutoAscend tables). DO NOT EDIT.\n'
  '// Contains data derived from NetHack 3.6.6 (via NLE); NetHack General Public License, see LICENSE and NOTICE.\n'
  '\npackage nle\n\n')

def goname(s):
    return s.replace(' ', '_')

w('const (\n')
for k, v in sorted(d['nh'].items()):
    w(f'\tNH_{k} = {v}\n')
w(')\n\n')
w('const (\n')
for k, v in sorted(d['O_consts'].items()):
    w(f'\tO_{k} = {v}\n')
w(')\n\n')
w('const (\n')
for k, v in sorted(d['monflag'].items()):
    w(f'\tMON_{k} = {v}\n')
w(')\n\n')
w('const (\n')
for k, v in sorted(d['SS'].items(), key=lambda kv: kv[1]):
    w(f'\tSS_{k} = {v}\n')
w(')\n\n')
w('const (\n')
for cls, members in d['action_enums'].items():
    for k, v in members.items():
        w(f'\tA_{cls}_{k} Action = {v}\n')
w(')\n\n')
w('var ActionsList = []Action{' + ', '.join(str(v) for _, v in d['actions']) + '}\n\n')
w('var ActionToIndex = map[Action]int{' + ', '.join(f'{k}: {v}' for k, v in d['action_to_index'].items()) + '}\n\n')

def bits(arr):
    return ''.join('1' if x else '0' for x in arr)
g = d['glyph']
for k in ['is_monster', 'is_pet', 'is_body', 'is_statue', 'is_object', 'is_normal_object']:
    w(f'var glyphBits_{k} = "{bits(g[k])}"\n')
w('var glyphToMon = []int16{' + ','.join(str(x) for x in g['to_mon']) + '}\n')
w('var glyphToObj = []int16{' + ','.join(str(x) for x in g['to_obj']) + '}\n\n')

def gostr(s):
    return json.dumps(s)

w('var Permonsts = [...]Permonst{\n')
for i, p in enumerate(d['permonst']):
    w(f'\t{{Idx: {i}, Mname: {gostr(p["mname"])}, Mlet: {ord(p["mlet"])}, Mlevel: {p["mlevel"]}, Mmove: {p["mmove"]}, Ac: {p["ac"]}, Mr: {p["mr"]}, '
      f'Geno: {p["geno"]}, Cwt: {p["cwt"]}, Cnutrit: {p["cnutrit"]}, Msound: {p["msound"]}, Msize: {p["msize"]}, Mresists: {p["mresists"]}, '
      f'Mconveys: {p["mconveys"]}, Mflags1: {p["mflags1"]}, Mflags2: {p["mflags2"]}, Mflags3: {p["mflags3"]}, Difficulty: {p["difficulty"]}, Mcolor: {p["mcolor"]}}},\n')
w('}\n\n')

w('var ObjClasses = [...]ObjClass{\n')
for o in d['objclass']:
    nm = o['oc_name']; ds = o['oc_descr']
    w(f'\t{{OcClass: {o["oc_class"]}, OcName: {gostr(nm or "")}, OcNameNone: {"true" if nm is None else "false"}, OcDescr: {gostr(ds or "")}, OcDescrNone: {"true" if ds is None else "false"}}},\n')
w('}\n\n')

fieldmap = {'name': None, 'desc': None, 'wt': None, 'damage_small': 'DamageSmall', 'damage_large': 'DamageLarge'}
intfields = ['kn', 'mg', 'bi', 'prob', 'cost', 'sdam', 'ldam', 'hitbon', 'typ', 'sub', 'metal', 'color', 'mgc', 'blk', 'power',
             'delay', 'ac', 'can', 'c', 'spec', 'mohs', 'chg', 'mat', 'mrg', 'clr', 'unk', 'tin', 'nutrition', 'level', 'dir',
             'worth', 'gval', 'nutr', 'glass']
def cap(f):
    return f[0].upper() + f[1:]
w('var Objects = [...]*Obj{\n')
for i, o in enumerate(d['objects']):
    if o is None:
        w('\tnil,\n'); continue
    f = o['fields']
    parts = [f'Idx: {i}', f'Kind: K{o["type"]}', f'Name: {gostr(f["name"] or "")}', f'NameNone: {"true" if f["name"] is None else "false"}',
             f'Desc: {gostr(f["desc"] or "")}', f'DescNone: {"true" if f["desc"] is None else "false"}']
    if f['wt'] is None:
        parts.append('WtNone: true')
    else:
        parts.append(f'Wt: {float(f["wt"])!r}')
    for k in ['damage_small', 'damage_large']:
        if k in f:
            parts.append(f'{fieldmap[k]}: {gostr(f[k])}')
    for k in intfields:
        if k in f:
            parts.append(f'{cap(k)}: {f[k]}')
    w('\t{' + ', '.join(parts) + '},\n')
w('}\n\n')
w('var objectSortOrder = []int{' + ','.join(map(str, d['object_sort_order'])) + '}\n\n')
w('var possFromGlyph = map[int][]int{\n')
for k, v in d['possibilities_from_glyph'].items():
    if isinstance(v, list):
        w(f'\t{k}: {{' + ','.join(map(str, v)) + '},\n')
w('}\n')
w('var possFromGlyphErr = map[int]string{\n')
for k, v in d['possibilities_from_glyph'].items():
    if isinstance(v, dict):
        w(f'\t{k}: {gostr(v["error"])},\n')
w('}\n')
w('var possibleGlyphsFromObject = map[int][]int{\n')
for k, v in d['possible_glyphs_from_object'].items():
    w(f'\t{k}: {{' + ','.join(map(str, v)) + '},\n')
w('}\n')
w('var objCategory = map[int]int{' + ', '.join(f'{k}: {v}' for k, v in d['get_category'].items()) + '}\n\n')

w('var gSetLists = map[string][]int{\n')
for k, v in d['G'].items():
    w(f'\t{gostr(k)}: {{' + ','.join(map(str, v)) + '},\n')
w('}\n\n')

w('var SokoMapsData = []SokoMapData{\n')
for s in d['soko_maps']:
    c = s['conv']
    if 'error' in c:
        w(f'\t{{Err: {gostr(c["error"])}}},\n'); continue
    grid = '{' + ', '.join('{' + ','.join(map(str, row)) + '}' for row in c['grid']) + '}'
    ans = '{' + ', '.join(f'{{{p[0]},{p[1]},{dd[0]},{dd[1]}}}' for p, dd in s['answer']) + '}'
    w(f'\t{{Grid: [][]int8{grid}, PosY: {c["pos"][0]}, PosX: {c["pos"][1]}, Answer: [][4]int{ans}}},\n')
w('}\n')
out.close()
